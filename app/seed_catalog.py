# ---------------------------------------------------------------- таблицы тиражей
def steps(prefix: str, table: dict[int, float], unit: str = "₽/шт", title: str = "") -> list[Row]:
    """Строки одной таблицы тиража: («Лён:4+4:500», «Лён, 4+4, от 500 шт», 8, ₽/шт).

    Ключ — по нему расчёт находит ступень; название — что видно на странице
    прайса. Ступень «от N» действует, пока тираж не дорос до следующей.
    """
    label = title or prefix.replace(":", ", ")
    out: list[Row] = []
    for edge, price in sorted(table.items()):
        key = f"{prefix}:{edge}" if prefix else str(edge)
        out.append((key, f"{label}, от {edge} шт", price, unit))
    return out


def table(prefix: str, edges: list[int], prices: list[float], unit: str = "₽/шт") -> list[Row]:
    assert len(edges) == len(prices), prefix
    return steps(prefix, dict(zip(edges, prices)), unit)



"""Телефон в едином виде — одно правило на всю систему.

Отдельным модулем, а не внутри clients.py, потому что правило нужно двум
несвязанным местам: справочнику клиентов (по номеру он узнаёт постоянного
заказчика) и платёжной ссылке (в неё подставляется номер получателя). Тянуть
ради одной функции всю логику клиентов вместе с моделями и базой незачем,
а заводить вторую копию правила — тем более: разъедутся.

Зеркало на фронте — web/src/lib/phone.ts.
"""

from __future__ import annotations

import re


def normalize_phone(raw: str | None) -> str:
    """Оставляет только цифры и приводит российские номера к виду 7XXXXXXXXXX.

    Нужно, чтобы +7 918 111-22-33, 8(918)1112233 и 89181112233 считались
    одним и тем же клиентом. В этом же виде номер ждут платёжные ссылки
    банков: `requisiteNumber=79881603218`.
    """
    text = (raw or "").strip()
    digits = re.sub(r"\D", "", text)
    # Иностранный номер — записан через «+» и не с 7/8: правила российской
    # нумерации к нему не применяем. Иначе десятизначный «+49 151 …»
    # превращался бы в «749151…» — формально верный, но чужой номер.
    if text.startswith("+") and digits and digits[0] not in "78":
        return digits
    if len(digits) == 11 and digits.startswith("8"):
        digits = "7" + digits[1:]
    if len(digits) == 10:
        digits = "7" + digits
    return digits

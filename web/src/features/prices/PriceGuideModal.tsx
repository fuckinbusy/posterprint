/* Справка для администратора: как устроен прайс и виды работ.

   Открывается кнопкой «i» на страницах «Прайс» и «Виды работ». Текст живёт
   здесь, а не в README: администратор в README не заглядывает, а вопрос
   «почему список пустой» возникает у него именно на этой странице.

   Слева — оглавление, справа — разделы; при прокрутке подсвечивается
   текущий. Содержание сверено с app/services/pricing.py (роли полей) и
   web/src/features/works/fieldKinds.ts (виды полей в конструкторе):
   если там что-то меняется, править нужно и здесь. */

import { useEffect, useRef, useState } from 'react';

import { ModalShell, useModal } from '@/app/ModalProvider';

type SectionKey =
  | 'idea'
  | 'groups'
  | 'items'
  | 'works'
  | 'kinds'
  | 'roles'
  | 'tiers'
  | 'sizes'
  | 'extras'
  | 'recipes'
  | 'checks';

const SECTIONS: { key: SectionKey; title: string }[] = [
  { key: 'idea', title: 'Как это устроено' },
  { key: 'groups', title: 'Разделы прайса' },
  { key: 'items', title: 'Позиции и ключи' },
  { key: 'works', title: 'Виды работ' },
  { key: 'kinds', title: 'Виды полей' },
  { key: 'roles', title: 'Как поле влияет на цену' },
  { key: 'tiers', title: 'Таблицы тиража' },
  { key: 'sizes', title: 'Размеры и единицы' },
  { key: 'extras', title: 'Доп. услуги и минимальный заказ' },
  { key: 'recipes', title: 'Пошагово: типовые задачи' },
  { key: 'checks', title: 'Проверка и типовые ошибки' },
];

/** Что открыть первым: прайс — с разделов, виды работ — с полей. */
export function PriceGuideModal({ start = 'idea' }: { start?: SectionKey }) {
  const [active, setActive] = useState<SectionKey>(start);
  const body = useRef<HTMLDivElement>(null);

  // подсветка пункта оглавления: последний раздел, чей заголовок уже
  // прошёл верх окна. Проще и предсказуемее IntersectionObserver, который
  // на промежуточных кадрах плавной прокрутки подсвечивал соседа.
  useEffect(() => {
    const root = body.current;
    if (!root) return;
    const nodes = Array.from(root.querySelectorAll<HTMLElement>('[data-guide]'));
    const onScroll = () => {
      // положение считаем от верха контейнера, а не offsetTop: у секций
      // offsetParent — окно целиком, и шапка окна сдвигала бы всё на раздел
      const top = root.getBoundingClientRect().top;
      let current = nodes[0];
      for (const n of nodes) if (n.getBoundingClientRect().top - top <= 48) current = n;
      // дошли до самого низа — активен последний, даже если он короткий
      if (root.scrollTop + root.clientHeight >= root.scrollHeight - 4) current = nodes[nodes.length - 1];
      setActive(current.dataset.guide as SectionKey);
    };
    root.addEventListener('scroll', onScroll, { passive: true });
    return () => root.removeEventListener('scroll', onScroll);
  }, []);

  useEffect(() => {
    if (start !== 'idea') jump(start, 'auto');
    // только при открытии
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const jump = (key: SectionKey, behavior: ScrollBehavior = 'smooth') => {
    const node = body.current?.querySelector<HTMLElement>(`[data-guide="${key}"]`);
    node?.scrollIntoView({ behavior, block: 'start' });
    setActive(key);
  };

  return (
    <ModalShell wide eyebrow="Справка администратора" title="Прайс и виды работ">
      <div className="guide">
        <nav className="guide-nav" aria-label="Оглавление">
          {SECTIONS.map((s, i) => (
            <button
              type="button"
              key={s.key}
              className={active === s.key ? 'active' : ''}
              onClick={() => jump(s.key)}
            >
              <i>{i + 1}</i>
              {s.title}
            </button>
          ))}
        </nav>

        <div className="guide-body" ref={body}>
          <section data-guide="idea">
            <h3>1. Как это устроено</h3>
            <p>
              Цена заказа складывается из трёх вещей, и все три вы настраиваете здесь, без формул и без
              программиста:
            </p>
            <ol className="guide-steps">
              <li>
                <b>Прайс</b> — разделы с позициями и ценами. «Баннер до 2 м: 450 ₽/м²», «Люверс: 15 ₽/шт».
              </li>
              <li>
                <b>Вид работ</b> — набор полей, которые сотрудник заполняет в заказе: материал, ширина,
                высота, ламинация, люверсы.
              </li>
              <li>
                <b>Роль поля</b> — правило, как выбранное значение превращается в деньги: умножить на площадь,
                на количество, взять один раз за заказ.
              </li>
            </ol>
            <p>
              Сотрудник выбирает вид работ, заполняет поля, нажимает «Рассчитать» — система идёт по полям
              сверху вниз, по каждому берёт цену из прайса и применяет роль. Получается смета построчно и
              итог. Итог — подсказка: менеджер может поправить его руками, в заказе хранится то, что он
              написал.
            </p>
            <div className="guide-note">
              Цены применяются сразу и для всех. Уже созданные заказы не пересчитываются: их стоимость
              зафиксирована в момент оформления.
            </div>
          </section>

          <section data-guide="groups">
            <h3>2. Разделы прайса</h3>
            <p>
              Раздел — это одна таблица цен с общей единицей: «Баннер» (₽/м²), «Люверсы и проклейка» (₽/шт,
              ₽/пог.м), «Ламинация» (₽/м²). Разделы бывают верхнего уровня («Рулонная печать») и вложенные в
              них — так на странице прайса не сто карточек, а шесть.
            </p>
            <p>
              У раздела есть <b>единица по умолчанию</b> — она подставляется новым позициям — и <b>вид</b>:
              обычные деньги или коэффициенты (× 1,8 за двустороннюю печать).
            </p>
            <div className="guide-rule">
              <b>Главное правило.</b> Поле-список в виде работ показывает сотруднику <em>все</em> позиции
              своего раздела. Поэтому у каждого списка должен быть свой раздел только с его вариантами. Если
              «Ламинацию» и «Плоттерную резку» положить в один раздел «Доп. к самоклейке», в списке
              «Ламинация» появится и резка. Галочкам и счётчикам это не мешает — они привязаны к одной позиции
              — им можно жить в общем разделе «Доп. работы».
            </div>
            <p>
              Раздел, на который ссылаются поля видов работ, удалить нельзя — сначала переназначьте поля.
              Система покажет, какие виды работ его используют.
            </p>
          </section>

          <section data-guide="items">
            <h3>3. Позиции и ключи</h3>
            <p>У позиции четыре части:</p>
            <table className="guide-table">
              <tbody>
                <tr>
                  <th>Ключ</th>
                  <td>
                    Короткое имя, которое видит сотрудник в списке и по которому расчёт находит цену: «Баннер
                    до 2 м», «Лён», «Ламинация до 2 м²». Менять ключ у позиции, которую уже выбирают в
                    заказах, нельзя — старые заказы перестанут её находить.
                  </td>
                </tr>
                <tr>
                  <th>Название</th>
                  <td>
                    Длинная подпись для себя и для сметы: «Ламинация, отпечаток до 2 м²». Можно менять
                    свободно.
                  </td>
                </tr>
                <tr>
                  <th>Цена и единица</th>
                  <td>
                    450 и ₽/м². Единица должна совпадать с тем, как поле считает: раздел «за м²», умноженный
                    на длину, даст бессмыслицу — система об этом предупредит в конструкторе.
                  </td>
                </tr>
                <tr>
                  <th>Включена / выключена</th>
                  <td>
                    Выключенная позиция пропадает из списков, но остаётся в базе — сезонный материал удобнее
                    выключить, чем удалять и заводить заново.
                  </td>
                </tr>
              </tbody>
            </table>
            <p>
              Позиция, к которой привязана галочка или счётчик в каком-то виде работ, помечена «занята» —
              удалить её нельзя, пока поле ссылается на неё. Каждое изменение цены пишется в историю: кто,
              когда, с какой на какую. Порядок позиций в списке — тот, что в разделе; перетащите, чтобы самое
              частое оказалось сверху.
            </p>
          </section>

          <section data-guide="works">
            <h3>4. Виды работ</h3>
            <p>
              Вид работ — то, что сотрудник выбирает первым шагом в новом заказе: «Печать баннера», «Визитки»,
              «Табличка». У каждого — своё название, короткая метка для карточки на доске, подпись у поля
              количества («Количество, шт» или «Тираж, шт») и список полей.
            </p>
            <p>
              Поля идут по порядку — и это порядок в форме заказа, и порядок расчёта. Порядок важен для
              коэффициентов (см. раздел 6). Вид работ можно спрятать: он исчезнет из выбора, но старые заказы
              с ним останутся читаемыми.
            </p>
            <p>
              У каждого поля: <b>подпись</b> (что видит сотрудник), <b>вид</b> (что это за поле, раздел 5), у
              полей с деньгами — <b>раздел прайса</b> и <b>способ расчёта</b>, у галочек и счётчиков — ещё и{' '}
              <b>позиция</b> прайса, откуда брать цену. Галочка «обязательное» не даёт сохранить заказ с
              пустым полем; у необязательного списка появляется вариант «нет».
            </p>
          </section>

          <section data-guide="kinds">
            <h3>5. Виды полей</h3>
            <p>
              В конструкторе вы отвечаете на один вопрос — «что это за поле?» — остальное подставляется само.
            </p>
            <table className="guide-table kinds">
              <thead>
                <tr>
                  <th>Вид поля</th>
                  <th>Что видит сотрудник</th>
                  <th>Откуда цена</th>
                </tr>
              </thead>
              <tbody>
                <tr>
                  <td>
                    <b>Выбор из прайса</b>
                  </td>
                  <td>Список: материал, бумага, формат</td>
                  <td>Выбранная позиция раздела</td>
                </tr>
                <tr>
                  <td>
                    <b>Доплата галочкой</b>
                  </td>
                  <td>Галочка: ламинация, проклейка, монтаж</td>
                  <td>Одна позиция, которую вы указали</td>
                </tr>
                <tr>
                  <td>
                    <b>Платное количество</b>
                  </td>
                  <td>Число: люверсы, отверстия, сгибы</td>
                  <td>Одна позиция × введённое число. Ноль — не нужно</td>
                </tr>
                <tr>
                  <td>
                    <b>Таблица тиража</b>
                  </td>
                  <td>Список: бумага или формат</td>
                  <td>Строка таблицы по тиражу — раздел 7</td>
                </tr>
                <tr>
                  <td>
                    <b>Уточнение таблицы</b>
                  </td>
                  <td>Список: цветность, стороны</td>
                  <td>Само не стоит, выбирает колонку — раздел 7</td>
                </tr>
                <tr>
                  <td>
                    <b>Ширина / Высота / Длина</b>
                  </td>
                  <td>Число с единицей</td>
                  <td>Не стоит; нужно для площади, периметра, длины</td>
                </tr>
                <tr>
                  <td>
                    <b>Выбор из своего списка</b>
                  </td>
                  <td>Список: тип изделия, раскладка</td>
                  <td>Без цены — пометка для цеха</td>
                </tr>
                <tr>
                  <td>
                    <b>Число без цены</b>, <b>Заметка</b>
                  </td>
                  <td>Число или строка</td>
                  <td>Без цены — записывается в заказ</td>
                </tr>
              </tbody>
            </table>
          </section>

          <section data-guide="roles">
            <h3>6. Как поле влияет на цену</h3>
            <p>
              У поля с деньгами есть <b>способ расчёта</b>. Ставка — это цена выбранной позиции; ниже — на что
              она умножается.
            </p>
            <table className="guide-table roles">
              <tbody>
                <tr>
                  <th>Умножить на количество</th>
                  <td>
                    ставка × тираж. Цена оттиска, цена визитки. У платного количества — ставка × введённое
                    число × тираж: восемь люверсов на каждом из трёх баннеров.
                  </td>
                </tr>
                <tr>
                  <th>Умножить на площадь</th>
                  <td>
                    ставка × ширина × высота × тираж. Баннер, плёнка, ламинация. Нужны поля «Ширина» и
                    «Высота».
                  </td>
                </tr>
                <tr>
                  <th>Умножить на периметр</th>
                  <td>
                    ставка × 2 (ширина + высота) × тираж. Проклейка края, кант. Нужны «Ширина» и «Высота».
                  </td>
                </tr>
                <tr>
                  <th>Умножить на длину</th>
                  <td>ставка × длина × тираж. Резка ленты, профиль. Нужно поле «Длина изделия».</td>
                </tr>
                <tr>
                  <th>Один раз за заказ</th>
                  <td>ставка как есть, тираж не влияет. Приладка, скрепление, выезд.</td>
                </tr>
                <tr>
                  <th>Коэффициент</th>
                  <td>
                    умножает всё, что накопилось <em>выше</em> этого поля по списку. Двусторонняя печать ×
                    1,8, срочность × 1,5. Позиции такого поля лежат в разделе вида «коэффициенты».
                  </td>
                </tr>
                <tr>
                  <th>По ступеням тиража</th>
                  <td>цена за штуку зависит от тиража — раздел 7.</td>
                </tr>
              </tbody>
            </table>
            <div className="guide-rule">
              <b>Порядок полей и коэффициент.</b> Коэффициент умножает только то, что выше него. Поставьте
              «Стороны × 1,8» сразу после «Бумаги» — удвоится и печать, и бумага. Поставьте его после
              «Печати», но до «Бумаги» — удвоится только печать. Перетаскивайте поля в конструкторе, чтобы
              задать, что именно множится.
            </div>
          </section>

          <section data-guide="tiers">
            <h3>7. Таблицы тиража</h3>
            <p>
              Визитки, флаеры, буклеты, сувениры считаются не «ставка × тираж», а по таблице: от 100 штук одна
              цена за штуку, от 500 — другая, от 1000 — третья. И таких таблиц много: у каждой бумаги и каждой
              цветности своя колонка.
            </p>
            <p>
              В прайсе это раздел, где <b>ключ позиции — это адрес ячейки</b>, части через двоеточие,
              последняя часть — «от скольких штук»:
            </p>
            <pre className="guide-code">
              {`Лён:4+0:100     18 ₽/шт     лён, односторонние, от 100 шт
Лён:4+0:500     11 ₽/шт     лён, односторонние, от 500 шт
Лён:4+4:100     24 ₽/шт     лён, двусторонние, от 100 шт
Лён:4+4:500     15 ₽/шт
Крафт:4+0:100   16 ₽/шт     другая бумага — своя колонка`}
            </pre>
            <p>В виде работ на такой раздел смотрят два вида полей:</p>
            <ul>
              <li>
                <b>Таблица тиража</b> — первая часть ключа. Варианты в списке («Лён», «Крафт») читаются из
                ключей раздела сами; руками их не набирают.
              </li>
              <li>
                <b>Уточнение таблицы</b> — следующие части («4+0», «4+4»), по одному полю на каждую часть, в
                том же порядке, что в ключе. Смотрят в тот же раздел.
              </li>
            </ul>
            <p>
              Сотрудник выбирает «Лён» и «4+4», вводит тираж 700 — система собирает адрес «Лён:4+4», берёт
              наибольшую подходящую ступень (500) и считает 15 ₽ × 700. Тираж меньше самой первой ступени —
              берётся первая. Если таблица простая, без бумаг и цветности, ключи — просто числа: «100», «500»,
              «1000».
            </p>
            <div className="guide-note">
              Добавить новую бумагу — значит добавить в раздел все её строки: «Дизайнерская:4+0:100»,
              «Дизайнерская:4+0:500» и так далее. Появится в списке сама. Одна пропущенная строка — и для
              этого сочетания расчёт скажет «в прайсе нет».
            </div>
          </section>

          <section data-guide="sizes">
            <h3>8. Размеры и единицы</h3>
            <p>
              Поля «Ширина», «Высота», «Длина изделия» сами ничего не стоят, но без них площадь, периметр и
              длину не посчитать. Конструктор не даст сохранить вид работ, где есть «умножить на площадь», а
              полей размера нет.
            </p>
            <p>
              У поля размера есть единица: мм, см или м — в ней сотрудник вводит число. Внутри всё приводится
              к метрам, поэтому баннер 3 × 1,5 м и плёнка 300 × 150 мм считаются одинаково верно. Единица
              прайса при этом всегда за м² или за погонный метр.
            </p>
            <p>
              Размер требуется только у полей, которые реально участвуют в расчёте: снятая галочка «Обрезка»
              не потребует длину, а включённая с пустой длиной остановит расчёт с подсказкой.
            </p>
          </section>

          <section data-guide="extras">
            <h3>9. Доп. услуги и минимальный заказ</h3>
            <p>
              Раздел <b>«Услуги»</b> — особенный: его позиции (макет, вёрстка, замер, монтаж) можно добавить к{' '}
              <em>любому</em> заказу блоком «Дополнительные услуги», с количеством. Заводить для них отдельный
              вид работ не нужно. В заказ записывается снимок названия и цены: изменение прайса на уже
              оформленные заказы не влияет.
            </p>
            <p>
              <b>Минимальный заказ.</b> Если в разделе с ключом «work» есть позиция «min_order», расчёт,
              получившийся меньше неё, поднимается до этой суммы отдельной строкой «Минимальный заказ». Нет
              позиции — нет минимума.
            </p>
          </section>

          <section data-guide="recipes">
            <h3>10. Пошагово: типовые задачи</h3>

            <h4>Добавить новый материал в существующий вид работ</h4>
            <ol className="guide-steps">
              <li>«Прайс» → раздел, из которого поле берёт варианты (в конструкторе он подписан у поля).</li>
              <li>«+ Позиция»: ключ — как будет называться в списке, цена, единица как у раздела.</li>
              <li>Готово: материал появился в списке у всех сотрудников. Ничего перезапускать не нужно.</li>
            </ol>

            <h4>Добавить платную опцию (галочку) в вид работ</h4>
            <ol className="guide-steps">
              <li>Убедитесь, что в прайсе есть позиция с ценой: например «Защитная ламинация», 1000 ₽/м².</li>
              <li>«Виды работ» → карандаш → «+ Поле» → вид «Доплата галочкой».</li>
              <li>Раздел прайса и позиция — та самая; способ расчёта — «Умножить на площадь».</li>
              <li>Если в этом виде работ ещё нет «Ширины» и «Высоты» — добавьте их.</li>
            </ol>

            <h4>Завести новый вид работ с нуля</h4>
            <ol className="guide-steps">
              <li>
                Сначала прайс: раздел под материалы (свой, только с ними) и, если нужно, раздел под доп.
                работы.
              </li>
              <li>«Виды работ» → «+ Новый вид работ»: название, метка для карточки, подпись количества.</li>
              <li>
                Поля сверху вниз: материал (выбор из прайса, обязательное), размеры, опции галочками,
                счётчики, в конце — коэффициенты, если есть.
              </li>
              <li>«Проверить расчёт» прямо в конструкторе: введите тестовые значения и посмотрите смету.</li>
            </ol>

            <h4>Завести продукт с таблицей тиража (визитки на новой бумаге)</h4>
            <ol className="guide-steps">
              <li>
                В разделе визиток добавьте строки «Новая бумага:4+0:100», «…:4+0:500», «…:4+4:100»,
                «…:4+4:500».
              </li>
              <li>Ничего больше: поле «Бумага» вида работ читает варианты из ключей раздела.</li>
            </ol>

            <h4>Поднять цены</h4>
            <ol className="guide-steps">
              <li>Цену меняют прямо в строке позиции: Enter или уход из поля сохраняет.</li>
              <li>Каждое изменение — в истории позиции (значок часов), с автором и датой.</li>
              <li>Заказы, оформленные до изменения, остаются со старой суммой.</li>
            </ol>
          </section>

          <section data-guide="checks">
            <h3>11. Проверка и типовые ошибки</h3>
            <table className="guide-table">
              <tbody>
                <tr>
                  <th>Список у поля пустой</th>
                  <td>
                    В разделе нет включённых позиций, или у поля не указан раздел. Для таблицы тиража — ключи
                    не заканчиваются числом.
                  </td>
                </tr>
                <tr>
                  <th>В списке чужие варианты</th>
                  <td>Два списка смотрят в один раздел. Разнесите по разделам — у каждого списка свой.</td>
                </tr>
                <tr>
                  <th>Расчёт пишет «в прайсе нет»</th>
                  <td>
                    Позиция удалена или выключена, либо у таблицы тиража нет строки для этого сочетания бумаги
                    и цветности.
                  </td>
                </tr>
                <tr>
                  <th>Сумма в разы больше или меньше ожидаемой</th>
                  <td>
                    Единица прайса не совпадает со способом расчёта (₽/м² при «умножить на количество»), либо
                    у размера стоит не та единица (мм вместо м).
                  </td>
                </tr>
                <tr>
                  <th>Коэффициент умножил не то</th>
                  <td>Он множит только поля выше себя. Переставьте его в конструкторе.</td>
                </tr>
                <tr>
                  <th>Расчёт требует размер, который не нужен</th>
                  <td>
                    Какое-то поле считает по площади или длине. Если оно необязательное и не выбрано — размер
                    не спросят; если обязательное — размеры нужны всегда.
                  </td>
                </tr>
                <tr>
                  <th>Удалили раздел, и вид работ сломался</th>
                  <td>
                    Кнопка «Восстановить недостающие» на странице прайса вернёт стартовые разделы и позиции,
                    которых не хватает. Свои позиции она не трогает.
                  </td>
                </tr>
              </tbody>
            </table>
            <p>
              Самый надёжный способ проверить настройку — «Проверить расчёт» в конструкторе вида работ: там
              видно смету построчно, откуда взялась каждая цифра.
            </p>
          </section>
        </div>
      </div>
    </ModalShell>
  );
}

